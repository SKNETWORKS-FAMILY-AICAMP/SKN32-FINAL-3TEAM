-- 0015 · `document.annex_no` — 별표 번호를 원문 머리글에서 읽어 담는다 (2026-09-14)
--
-- 왜 — 별표는 조·항·호가 아니라 「2.가.1」 같은 계층을 쓴다. 그래서 `citation()` 이 좌표를
--      세우지 못하고, 좌표 없는 근거는 판정에 못 간다. 실측(2026-09-14): 상위 5건 중 **4건이
--      별표**였고 전부 버려졌다 — 하필 013453 [별표 1]「부당한 표시 또는 광고의 내용」처럼
--      **광고 문구가 실제로 걸리는 자리**다. 별표 301행(12.5%)이 영구히 근거로 못 갔다.
--
-- 🔴 **번호가 필요한 이유 — 경로가 유일하지 않다.** 실측:
--        013475 / 2.가.1 → 「수입식품안전관리 특별법 제2조제1호에 따른 …」  (annex:013475_0003)
--        013475 / 2.가.1 → 「과자류, 빵류 또는 떡류: 추잉껌」              (annex:013475_0004)
--    같은 `law_id`·같은 경로인데 **다른 별표**다. 번호 없이 인용하면 두 근거가 같은 좌표로
--    찍힌다 — D-224 가 막으려는 「틀린 인용」 바로 그것이다.
--
-- 🚨 **왜 `document` 이고 `chunk` 가 아닌가** — 별표 번호는 **문서 하나에 하나**다.
--    `chunk` 에 두면 301행에 같은 값이 중복되고, 한쪽만 고쳐지는 날이 온다 (D-99).
--    검색은 `_JOINS` 에 `document` 를 더해 읽는다 — 거버넌스를 질의로 거는 것과 같은 어법이다.
--
-- ⛔ **파일명 일련번호(`annex_no` in `law_norm/*.jsonl`)로 채우지 않는다.** 머리글이 있는 24건은
--    전부 일치했지만 **머리글이 없는 파일이 34건**이고 그중 하나는 산문이다. 없는 것을
--    「아마 같을 것」으로 채우면, 그 별표가 들어오는 날 조용히 틀린 번호가 인용된다.
--    ★ 그래서 NULL 을 허용하고, 읽는 쪽이 NULL 이면 **인용을 세우지 않는다** (D-72 fail-closed).
--
-- 🧊 **동결 후 첫 새 마이그레이션이다.** `0001` 은 `db/schema_0001.sql` 만 읽으므로, 이제
--    스키마 변경은 **`db/schema.sql` + 이 파일** 둘로만 들어온다. `db-drift` 가 대조한다.

ALTER TABLE document ADD COLUMN IF NOT EXISTS annex_no SMALLINT;

COMMENT ON COLUMN document.annex_no IS
  '별표 번호 — 원문 머리글에서 읽은 값만. NULL 은 머리글에 번호가 없다는 뜻이고 '
  '파일명 일련번호로 채우지 않는다 (0015 · D-224).';
