#: 서술어로 끝나는 꼴 — 명사구(제품명 · 성분 나열 · 표제)가 아니라 무엇을 말하는 문장이다
PREDICATE = re.compile(
    r"(다|요|음|함|됨|임|니다|세요|죠|까|게|고|며|서|지|네|라|!|\?|~)\s*[.!?~]*\s*$"
)

#: 광고 표지 낱말 — 명사구여도 주장을 싣는 꼴(최상급 · 수치 · 효능 · 인증 · 보장 …)
AD_CUE = re.compile(
    r"(최고|최초|최상|최대|최저|1위|No\.?1|넘버원|100\s*%|\d+\s*%|완벽|보장|제거|효과|효능|개선|인증|특허|유일|독보|만족|추천|무료"
    r"|할인|증정|보증|1등|대한민국|세계)"
)


def is_veto(text: str) -> bool:
    """거부 가드에 걸리는가 — 걸리면 인코더가 기록 · 확정에 들어오지 않는다(보류 · 위험도 칸은 사전 몫만)."""
    return bool(VETO.search(text or ""))


def claim_guard(text: str) -> bool:
    """주장 가드 — 인코더 하한을 **기록에 들일 문장**인가 (D-348 결정 5 R1 층 · 「주장인가만」 가린다 · 유형 무관).

    = 주의 · 상담 문구가 아니다 ∧ 거부 가드에 안 걸린다 ∧ (서술어로 끝난다 ∨ 광고 표지 낱말이 있다).
    🔴 빈 글자는 거짓이다 — 모르면 들이지 않는다 (D-220).
    """
    t = (text or "").strip()
    if not t or is_caution(t) or is_veto(t):
        return False
    return bool(PREDICATE.search(t) or AD_CUE.search(t))


