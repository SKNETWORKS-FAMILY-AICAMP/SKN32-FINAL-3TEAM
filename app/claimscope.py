def cert_not_drug(text: str) -> bool:
    """인증 · 실증 꼴뿐인 문장인가 — 참이면 화장품 전제의 인코더 의약품 오인을 절대형(C)으로 세우지 않는다 (🆕 2026-10-19 · D-348 보충 25).

    🔴 막기만 한다 — 위반이 없다는 뜻이 아니다. 막힌 문장은 확신 부족 보류(질문 쪽)로 남는다(보충 1 비대칭). 글자가 없으면 거짓(막지 않음).
    """
    t = text or ""
    if not CERT_SUBST.search(t):
        return False
    # 기관 이름 속 「의약」(식품의약품안전처)은 의학 낱말이 아니다 — 지침 제4호 절의 예시 문장 그대로다
    n = _norm(t).lower().replace("식품의약품안전처", "")
    return not (MED_GENERAL.search(n) or any(w in n for w in COSMETIC_MED_CUES))


def _clause(text: str, start: int, end: int) -> tuple[int, int]:
    a = max([m.end() for m in CLAUSE_BOUND.finditer(text, 0, start)] or [0])
    m = CLAUSE_BOUND.search(text, end)
    return a, (m.start() if m else len(text))


def confirm_block(text: str, span: tuple[int, int] | None) -> str | None:
    """사전 적중 하나의 확정을 막는 사유 — 정체부정 · 효능부정 · 약명 · 주의 · 부작용 · 통계정보 · 대상 · 고지. 막지 않으면 None.

    🔄 2026-10-18 (D-348 보충 23) — 동사로 끝나는 적중(조사 낀 꼴) 뒤의 정체 부정 · 효능 부정 · 약 이름과 확정만 막는 주의 꼴을 더했다.

    🔴 구간을 모르면(`span` 없음) 막지 않는다 — 절을 정할 수 없다 · 확정은 종전대로. 판정 대상 아님(`is_caution`)과 섞지 않는다.
    """
    if span is None:
        return None
    t = text or ""
    s, e = span
    a, b = _clause(t, s, e)
    # 🔴 부정이 **타사**를 향하면(「경쟁사 제품은 효과 없음」) 부인이 아니라 비방이다 — 부정 사유로 막지 않는다(타사 표지는 `factcheck` 한 곳 · D-99)
    other = bool(factcheck.COMPETITOR.search(t[a:b]))
    if not other and (NEG_IDENTITY.search(t[e:b]) or NEG_IDENTITY_FOR.search(t[e:b])):
        return "정체부정"
    if not other and NEG_EFFICACY.search(t[e:b]):
        return "효능부정"
    # 🆕 2026-10-18 (보충 23 결정 1) 동사로 끝나는 적중 뒤의 정체 부정 · 효능 부정
    if not other and NEG_IDENTITY_VERB.search(t[e:b]):
        return "정체부정"
    if not other and NEG_EFFICACY_VERB.search(t[e:b]):
        return "효능부정"
    cl = t[a:b]
    if (
        DRUG_SUFFIX if DRUG_VERB_END.search(re.sub(r"\s", "", t[s:e])) else DRUG_SUFFIX_BARE
    ).search(t[e:b]):
        return "약명"
    if DRUG_VERB_ATTR.search(t[e:b]):
        return "약명"
    if CAUTION.search(cl) or CONFIRM_CAUTION.search(cl):
        return "주의"
    if SIDE_EFFECT.search(cl):
        return "부작용"
    if STAT_INFO.search(cl):
        return "통계정보"
    if TARGET_FORM.search(t[e:b]) and not TARGET_CLAIM.search(cl):
        return "대상"
    if any(p and p in t for p in NOTICE_PHRASES):
        return "고지"
    return None
