#: 섭취 주의 · 전문가 상담 · 과량 섭취 경고 꼴 (D-348 보충 1 결정 1 · L0 (가)). 🔴 꼴을 넓히기 전에 위반에 걸리는지 잰다 —
#: 「알레르기」 단독은 위반 문장(「알레르기 유발 물질 99.95% 정화」)에 걸려 「알레르기를 나타내 · 알레르기가 있는」 꼴로 좁혔다.
CAUTION = re.compile(
    r"섭취(에|를|시)?\s*주의"
    r"|주의(하십시오|하시기|할 것|하세요)"
    r"|삼가"
    r"|피할 것|피하십시오|피하시기"
    r"|전문가와 상담|의사(와|의)\s*상담|상담(할 것|하십시오|하시기)"
    r"|복용하(시는|는) 분"
    r"|과(량|다)\s*섭취 시"
    r"|알레르기를? (나타내|있는)"
    r"|나타날 수 있"
    r"|섭취를 (피|중단)"
    r"|준수하여"
    r"|바람직"
)


def is_caution(text: str) -> bool:
    """주의 · 상담 문구 꼴인가 — 판정 대상 아님의 **후보**다. 사전 자격 적중 여부는 부르는 쪽이 본다."""
    return bool(CAUTION.search(text or ""))


