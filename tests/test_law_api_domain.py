TAX_NAMES = [
    "광고대행수수료와 자문료는 통상적인 비용으로 필요경비에 해당하며 당직비는 소득세 과세대상임",
    "광고매체대행사가 수취한 매입세금계산서가 사실과 다른 세금계산서에 해당하는지 여부",
    "광고매체제공업과 여객운송업을 겸업하는 사업자의 유류비 등 매입세액 안분 방법",
    "신문사의 광고수입금액 누락 및 가공경비 계상에 따른 법인세 탈루 여부",
    "특정거래업체에 특정조건으로 지출한 광고선전비가 접대비에 해당하는지 여부",
    "광고선전비의 손금산입 적정 여부",
]

