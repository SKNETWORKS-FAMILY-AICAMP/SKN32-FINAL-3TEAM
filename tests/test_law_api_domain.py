def test_tax_beats_industry() -> None:
    """세무 어휘는 업종어를 **이긴다.**

    「**화장품** 외판원이 **부가가치세**법상의 사업자인지 여부」 — 실측된 사건명이다.
    `INDUSTRY_WORDS` 를 먼저 보면 `화장품` 때문에 무조건 통과한다.
    """
    assert _in_domain("화장품 외판원이 부가가치세법상의 사업자인지 여부") is False


def test_industry_beats_outdoor_ad() -> None:
    """업종어는 옥외광고물을 **이긴다.** 🚨 회귀 방지 — 순서를 바꾸다 이걸 깨기 쉽다.

    세무를 맨 앞에 넣으면서 「제외는 다 앞으로」로 정리하고 싶어지는데,
    그러면 이 사건이 오탈락한다. 두 규칙의 방향이 반대라는 것이 요점이다.
    """
    assert _in_domain("식품위생법 위반업소 행정처분 및 불법옥외광고물 자진철거 계고처분") is True


def test_outdoor_ad_without_industry_is_dropped() -> None:
    """업종어가 없으면 옥외광고물은 그대로 빠진다 — 기존 규칙이 살아 있는지 본다."""
    assert _in_domain("광고물등표시금지지역장소의상업광고표시허용심의취소") is False


