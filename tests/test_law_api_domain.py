    """⛔ 2026-09-06 실제 오탈락. `--audit` 이 없었으면 「잘 걸렀다」로 지나갔다.

    🚨 `가처분` 은 두 글자가 넘는데도 **단어가 아니었다** —
       허가처분 · 부가처분 · 인가처분 · 불허가처분 안에 그대로 들어 있다.
       게다가 그때 `가처분` 은 업종어를 이기는 칸에 있어서, `의약품` 이 박힌
       두 사건이 **구제되지 못하고** 빠졌다. 순서를 세게 준 만큼 값을 치른 자리다.
    """
    assert _in_domain(name) is True


