"""`collect.law_api._in_domain` — 사건명 어휘 필터 (2026-09-06).

🚨 **거버넌스 게이트가 아니다.** `gate` 마크를 붙이지 않는다 (D-89).

왜 생겼나 — 어휘를 `decc`(행정심판재결례) **하나만 보고** 정한 뒤 `prec`(판례)에
그대로 옮겼다. 재결례에는 세무·민사가 거의 없고, 판례에는 **같은 코퍼스에 있다.**
그 결과 이미 받은 `prec` 92건 안에 이런 것들이 섞였다 —

    「광고대행수수료와 자문료는 통상적인 비용으로 필요경비에 해당하며…」
    「신문사의 광고수입금액 누락 및 가공경비 계상에 따른 법인세 탈루 여부」
    「사죄광고」 · 「광고료」 · 「현상광고보수금」 · 「광고금지가처분」

🚨 이 파일에 적힌 사건명은 **전부 실측이다.** `--target prec` 92건과 `--target decc`
   120건의 사건명을 눈으로 훑어 뽑았다. 지어낸 예시를 섞지 않는다 — 어휘 필터는
   실제 코퍼스의 말버릇을 따라가는 것이지 우리가 상상한 말버릇을 따라가는 것이 아니다.

🚨 이 모듈이 지키는 불변식은 **판정 순서**다 (D-118 ③).
   ① 세무·민사(`EXCLUDE_STRONG`)는 업종어를 **이긴다.**
   ② 업종어(`INDUSTRY_WORDS`)는 옥외광고물(`EXCLUDE_WORDS`)을 **이긴다.**
   두 관측이 서로 반대이므로 한 통에 합치면 어느 쪽이든 깨진다.
"""

