def test_label_change_survives_when_industry_is_present() -> None:
    """🚨 동음어를 **약한 칸**에 둔 이유.

    「건축물표시변경」은 빠져야 하지만, 식품 표시변경 사건은 우리 것이다.
    센 칸에 두면 뒤엣것까지 조용히 사라진다 — 관측이 없어도 이 방향은 지킨다.
    """
    assert _in_domain("건축물표시변경신청수리불가처분취소") is False
    assert _in_domain("식품등의표시변경명령취소") is True


def test_merged_criminal_case_with_tax_charges_survives() -> None:
    """🚨 `조세` 를 제외 어휘에 넣지 않은 판단의 값 — 실측 사건명이다.

    형사 판결은 병합된 죄명을 전부 이어 붙인다. 앞이 조세라고 빼면
    **뒤에 붙은 표시광고법 위반**을 통째로 잃는다.
    """
    assert (
        _in_domain(
            "특정범죄가중처벌등에관한법률위반(조세)·특정경제범죄가중처벌등에관한법률위반(횡령)"
            "·조세범처벌법위반·표시·광고의공정화에관한법률위반"
        )
        is True
    )


