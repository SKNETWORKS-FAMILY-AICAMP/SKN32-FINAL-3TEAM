def _norm(s: str) -> str:
    """가운뎃점 변이(`ㆍ` U+318D · `・`)를 `·` 로, 공백을 지운다 — 법제처 정식 명칭이 `ㆍ` 를 쓴다."""
    return re.sub(r"\s+", "", s.replace("ㆍ", "·").replace("・", "·"))


_NAMES = sorted(((_norm(k), v) for k, v in NAME_TO_LAW.items()), key=lambda kv: -len(kv[0]))


def law_of_basis(basis: str) -> str | None:
    """근거 문자열(「식품표시광고법 제8조제1항제4호」) → 법 축. 모르면 **None** — 기본값으로 떨어지지 않는다 (D-220).

    ★ **가장 긴 이름부터** 앞머리로 맞춘다 — 「표시광고법」이 「식품표시광고법」의 꼬리라 짧은 것부터 보면 틀린다.
    🚨 이름 바로 뒤가 「제」(조문 번호)가 아니면 None — 「○○법 시행령 …」을 법률 조문으로 읽지 않는다.
    """
    b = _norm(basis)
    for name, law in _NAMES:
        if b.startswith(name) and b[len(name) :].startswith("제"):
            return law
    return None
