#:    하나뿐이라 그 자리를 못 잡는다.
#:    ★ **새 판단이 아니다** — `mask_paren_alias` 의 주석과 같은 논리다:
#:      *「이미 지우기로 판정된 그 법인의 다른 표기다.」* 앵커가 근거이므로 이 표는
#:      **앵커에 그 토막이 든 문서 안에서만** 쓰인다 — 「SKYEDU」는 안 건드린다.
#:    ⛔ **전역 회사명 목록이 아니다.** 2026-09-17 오전에 그것을 켰다가 「2015년 가장 많이
