#:        (「부동산뱅크」·「랭키닷컴」·「부킹닷컴」·「스피드뱅크」).
#:
#: 🔴 **치환이지 삭제가 아니다** (D-142). 접미사가 잡는 문구 중 상당수가 **광고 카피 본체**다 —
#:    「군포시 금정동 소재 율곡주공3단지 아파트 76㎡(19,000만원)」은 허위매물 광고 그 자체다.
#:    통째로 버리면 그 사건의 판정 대상이 사라진다. **고유부만** `[업체]` 로 바꾸고
#:    접미사는 남긴다 — 「[업체]아파트 76㎡(19,000만원)」이면 판정 가치가 그대로 산다.
#:
#: 🚨 **`ftc` 축에서만 쓴다.** `mfds` 에서는 **제품명이 곧 위법 문구**라(「혈압케어 혈액 순환
