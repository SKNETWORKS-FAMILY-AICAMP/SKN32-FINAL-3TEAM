#:    두었다 — ftc 의 상표는 **영업표지**, mfds 의 상표 자리는 **제품명이자 위법 문구**다.
#: ⛔ **「캐슬」을 뺐다** (2026-09-17 팀장 판정). 표본에서 잡힌 둘이 **전부 오탐**이다 —
#:    「스카이캐슬」·「홍보캐슬」. 브랜드(「롯데캐슬」)로 쓰이기도 하지만 **일반어로도 쓰여서**
#:    앞말만 보고는 못 가른다. 진짜 브랜드가 표본에 나타나면 그때 다시 본다 (D-40 의 어법).
#: 🔴 **접미사는 두 부류다 — 무엇을 가릴지가 반대다** (2026-09-17 팀장 판정).
#:
#:    ⛔ 한 부류로 다루다가 **거꾸로 가리고 있었다** — 「파주힐스테이트」에서 「파주」를 가리고
#:       「힐스테이트」를 남겼다. **파주는 지명이고 힐스테이트가 브랜드다.** 가려야 할 쪽을
#:       남기고 남겨야 할 쪽을 가린 것이다.
#:
#:      ① **유형어·공급주체** — 그 말 자체는 일반어다. **앞이 이름**이므로 앞을 가린다.
#:         「보람아파트」→「[업체]아파트」 · 「율곡주공」→「[업체]주공」 · 「부킹닷컴」→「[업체]닷컴」
#:         ★ 「주공」은 「시영」과 같은 부류다 — 공급 주체를 가리키는 말이라 이름이 아니다.
#:      ② **브랜드** — 그 말 자체가 이름이다. **자신을 가린다.**
#:         「파주힐스테이트」→「파주[업체]」 · 「사천대우푸르지오」→「사천대우[업체]」
#:
#:    ⬜ **남는 한계** — ②에서 브랜드 앞에 붙은 **기업명**은 못 가린다(「**대우**푸르지오」의
#:       「대우」 · 「**코오롱**하늘채」의 「코오롱」). 법인격 표기가 없어서다. 같은 문서에
#:       「(주)대우건설」이 있으면 `doc_org_names` 2패스가 잡고, 없으면 못 잡는다 — [P6] 자리다.
#:      ③ **건설사 + 브랜드** — 브랜드 앞에 붙은 기업명도 이름이다 (2026-09-17 팀장 판정).
#:         「사천**대우푸르지오**」에서 **대우도 브랜드**이므로 「사천[업체]」가 맞다.
#:         ⛔ 규칙만으로는 「사천|대우」의 경계를 못 가른다 — 「대우가 기업명」이라는 것은
#:            **사전 지식**이다. 그래서 좁은 건설사 목록을 둔다. 이것이 [P6] 의 씨앗이고,
#:            늘어나면 그때 사전으로 올린다 (D-99).
#:         🚨 **기업명 단독은 안 가린다.** 실측에서 「삼성」10·「코오롱」5·「SK」3 이 브랜드
#:            없이 단독으로 나오는데(「삼성전자 국내외 바이어 수요독점」), 그것까지 가리면
#:            **광고 문구 본체를 먹는다.** 브랜드와 **짝일 때만** 가린다.
_SUF_TYPE = r"(?:아파트|오피스텔|주공)"
_SUF_ONLINE = r"(?:닷컴|뱅크)"
#: ② 단독으로도 이름인 브랜드
_SUF_BRAND = r"(?:자이|하늘채|푸르지오|래미안|힐스테이트|위브)"
#: ③ 건설사 — 브랜드 앞에 오면 함께 가린다
#: 🔴 **기업명은 두 부류다 — 단독으로 가려도 되는 것과 아닌 것** (2026-09-17 · 문맥 79개 전수).
#:
#:    ⛔ 단독으로 다 가렸다가는 **광고 문구 본체를 먹는다.** 실측에서 둘이 나왔다 —
#:         「**현대**의학으로 안되는 불치병 치유척척!!」   ← 현대 = modern
#:         「영단기의 **반도** 안되는 신토익 강의 수」      ← 반도 = 반(半)도
#:       둘 다 **실제 위법 광고 문구**다. 가리면 판정 대상이 사라진다 (D-157 의 병).
#:       「대우(待遇)」·「한라(한라산)」·「서희(인명)」도 같은 자리에 있다.
#:
#:    ⛔ **단독 가림은 폐기했다** (2026-09-17 · 실측으로 기각). 「일반어로 안 쓰이는 기업명만
#:       단독으로 가린다」를 시도했더니 **경계가 없어서 문구가 망가졌다** —
#:         「2015년 가장 많이 검색**한 화학**강사」 → 「검색[업체]학강사」   ← 「한화」가 잡혔다
#:         「매년 **SKY**, 의치대 합격생 다수 배출」 → 「[업체]Y, 의치대」    ← SKY 는 대학 약칭
#:         「유니버설스튜디오 코리아 리조트(U**SK**R)」 → 「U[업체]R」
#:       한글에는 단어 경계가 없고 영문 약칭은 두 글자라 다른 말 안에 그대로 들어간다.
#:       **짝이 경계를 준다** — 그래서 기업명은 브랜드·업종어와 **붙어 있을 때만** 가린다.
_CORP = (
    r"(?:대우|코오롱|현대|삼성|GS|지에스|롯데|포스코|SK|에스케이|한화"
    r"|대림|두산|쌍용|금호|한라|호반|우미|중흥|서희|르노)"
)
#: 🚨 업종어는 **남긴다** — 「삼성전자」→「[업체]전자」. 무엇을 하는 회사였는지가 문맥이고,
#:    그것까지 지우면 「[업체] 국내외 바이어 수요독점」이 되어 판정 근거가 얕아진다.
_CORP_BIZ = (
    r"(?:전자|건설|화재|생명|카드|은행|증권|물산|홀딩스|제약|화학|케미칼|중공업"
    r"|해운|항공|백화점|마트|타이어|자동차|이엔씨|종합상조|상조|패션|리조트|개발)"
)
#: 🚨 **일반어와 충돌하는 브랜드는 건설사와 짝일 때만** 가린다.
#:    「스카이캐슬」·「홍보캐슬」이 팀장 판정으로 오탐이었다 — 「캐슬」 단독은 이름이 아니다.
#:    「롯데캐슬」은 짝이라 잡힌다.
_BRAND_PAIRED = r"(?:캐슬|더샵|아이파크|블루밍|베르디움|리슈빌|해피트리)"
#: 🚨 **공백을 넣지 않는다.** 위 실측의 「이 사건 아파트」가 그 대가다.
#: ① 앞을 가리는 꼴. 🚨 **공백을 넣지 않는다** — 위 실측의 「이 사건 아파트」가 그 대가다.
_ORG_BARE_SUFFIX = re.compile(r"([가-힣A-Za-z0-9]{2,10})(" + _SUF_TYPE + "|" + _SUF_ONLINE + ")")
#: ② 자신을 가리는 꼴. 앞말은 지명일 수 있으므로 **건드리지 않는다**.
#: 🚨 **순서가 있다** — 긴 것부터. 「삼성전자」를 「삼성」으로 먼저 먹으면 업종어가 흩어진다.
_ORG_BARE_BRAND = re.compile(
    "(?:" + _CORP + r")?\s?(?:" + _SUF_BRAND + ")|(?:" + _CORP + r")\s?(?:" + _BRAND_PAIRED + ")"
)
#: 기업명 + 업종어. 업종어는 캡처 밖에 둬서 **남긴다**.
#: 🚨 **목록 안의 기업명이 이어 붙으면 통째로** 잡는다 (`+`).
#:    ★ 「**르노삼성**자동차」→「[업체]자동차」 — **르노(Renault S.A.)도 브랜드다**
#:       (2026-09-17 팀장 판정). 합작사는 양쪽 다 기업명이므로 연쇄를 통째로 가린다.
#:    ★ 목록에 없는 말은 안 먹는다 — 「**사천**대우푸르지오」의 「사천」(지명)도 남는다.
_ORG_BARE_CORP = re.compile("(?:" + _CORP + ")+(?=" + _CORP_BIZ + ")")


#: 🚨 **공공기관·학회는 남긴다** (2026-09-17 판정 ⬜). 광고가 **신뢰성의 근거로 인용한 것**이라
#:    가리면 「무엇을 근거로 삼았는가」가 사라진다 — 그것이 곧 실증 판정의 대상이다 (D-228).
#:    ⬜ 목록이지 규칙이 아니다. 늘어나면 그때 규칙으로 올린다 (D-99).
_PUBLIC_KEEP = frozenset({"온나라부동산정보통합"})

#: 🆕 **접미사 앞이 고유명이 아니라 일반어인 것** (2026-09-17 팀장 판정).
#:    ⛔ 「원룸아파트」·「명품아파트」는 **건물 유형과 광고 수식어**이지 단지명이 아니다 —
#:       「유일보노빌 **원룸아파트** 내 상가」 · 「1515세대 all 전세형 **명품아파트**」.
#:       가리면 광고 수식어(「명품」)가 사라지는데 **그것이 곧 거짓·과장 판정의 대상**이다.
#:    🔄 2026-09-17 「시영」 추가 (팀장 확인) — **「시에서 경영하거나 건립했다」는 뜻**이라
#:       단지명이 아니라 **공급 주체를 가리키는 일반어**다. 「원룸」과 같은 부류다.
#:    🚨 이 목록은 **오탐을 막는 자리이지 사전이 아니다.** 진짜 사전은 [P6] 다.
#:    🔄 2026-09-17 「최고층」 추가 (팀장 확인) — 「명품」과 같은 **광고 수식어**다.
#:       가리면 최상급 표현이 사라지는데 **그것이 곧 거짓·과장 판정의 대상**이다.
#:    🔄 2026-09-17 「분양」·「지역주택」·「주상복합」 추가 (팀장 확인) — 「원룸」과 같은 부류다.
#:       「분양아파트」·「지역주택조합아파트」·「주상복합아파트」의 앞은 **건물·사업 유형**이다.
_GENERIC_HEAD = frozenset(
    {"원룸", "명품", "홍보", "스카이", "시영", "최고층", "분양", "지역주택", "주상복합"}
)

#: 🆕 문서가 **스스로 선언한** 고유명 — 「X(이하 "이 사건 Y"」 의 X.
#: ★ `anchor_ftc` 가 사건명에서 하는 일과 같은 어법이다 — 문서가 「이것은 고유명이다」라고
#:   밝힌 자리만 쓴다. 실측 27개 · 26문서로 **좁지만 오탐이 거의 없다.**
#: ⛔ 「전국 객실가동률 1위" 등으로 광고하였다」처럼 **광고 문구가 통째로 잡히는 것**이 섞인다 —
#:    그래서 서술어가 있으면 버린다. 아래 `_DEF_DROP` 이 그 자리다.
_DEF_CLAUSE = re.compile(
    r"([가-힣A-Za-z0-9][^()\n]{1,40}?)\(\s*이하\s*[\u201c\"\']?\s*(?:이\s?사건|본\s?건)"
)
_DEF_DROP = re.compile(r"광고|하였다|합니다|입니다|등으로|[!！%]")


def bare_org_names(text: str) -> list[str]:
    """법인격 표기 없이 쓰인 제3자 이름 후보. **세는 쪽과 지우는 쪽이 같은 표를 본다** (D-99).

    🚨 후보다 — 「이것이 회사다」가 아니라 「회사일 자리다」. 판정은 사람이 한다 (D-66).
    """
    out: list[str] = []
    for pat in (_ORG_BARE_BRAND, _ORG_BARE_CORP):
        out += [m.group(0) for m in pat.finditer(text)]
    for head, _suf in _ORG_BARE_SUFFIX.findall(text):
        if (
            head not in _PUBLIC_KEEP
            and head not in _GENERIC_HEAD
            and head not in out
            and not MARK_RE.search(head)
        ):
            out.append(head)
    for m in _DEF_CLAUSE.finditer(text):
        name = m.group(1).strip()
        # ⛔ **이미 지워진 자리를 다시 잡지 않는다** (2026-09-17 실측). 자국을 안 거르면
        #    「[업체] 타운」·「[주소]스 오피스텔」이 새 고유명으로 세어져 **지운 것을
        #    「아직 남아 있다」로 보고**한다 — 계수기가 자기 일을 되먹는다 (D-166).
        # ⛔ `MARK_RE` 만으로는 부족하다 — 캡처가 `[` 를 건너뛰고 「업체] 타운」부터 잡으면
        #    **닫는 대괄호만 남아** 자국으로 안 읽힌다. 대괄호가 한 쪽이라도 있으면 버린다.
        if (
            name
            and not _DEF_DROP.search(name)
            and not MARK_RE.search(name)
            and "[" not in name
            and "]" not in name
            and name not in out
        ):
            out.append(name)
    return out


def residual_bare_orgs(text: str) -> list[str]:
    """마스킹 뒤에도 **법인격 없이** 남아 있는 제3자 이름 후보. 🚨 세기만 한다.

    ★ `residual_orgs()` 의 짝이다 — 그쪽은 법인격 표기가 **있는** 것, 이쪽은 **없는** 것.
      주석이 *「③ 앵커에 없는 제3자 — 지금까지 한 번도 안 재 본 것」* 이라 적어 둔 자리를 잰다.
    🚨 **하한이다.** 접미사도 정의절도 없는 이름(「부동산114」·「알바천국」·「IIHS」)은
       이 검사도 못 잡는다 — 그건 [P6] 사전 자리다. 못 하는 것을 못 한다고 적는다.
    """
    bare_mark = MASK_ORG.strip("[]")
    return [x for x in bare_org_names(text) if bare_mark not in x]


def mask_org_bare(
    text: str, names: list[str], log: list[dict] | None = None
) -> tuple[str, list[str]]:
    """문서 자기 사전으로 맨몸 언급을 `[업체]` 로. **무엇을 지웠는지 함께 돌려준다.**

    🚨 지운 목록을 돌려주는 것이 설계다 — 결정요청 §4 가 *「지우는 것과 세는 것을
       한 짝으로」* 라고 적은 그 자리다. 세는 쪽이 없으면 커버리지가 오른 만큼
       안심하게 되고, 안심한 만큼 확인을 안 하게 된다.
    """
    used: list[str] = []
    for n in names:
        if n in text:
            _note(log, "맨몸(2패스)", n, MASK_ORG)
            text = text.replace(n, MASK_ORG)
            used.append(n)
    return text, used


#: 🚨 **영업표지**는 따옴표 안에 있고 앞에 그 말이 붙는다 (실측) —
#:      「자신의 **영업표지 '청년피자'**를 사용하여」
#:      「'에듀플렉스, 에듀코치 **영업표지** …」
#: 🚨 문맥 없이 따옴표만 보고 지우면 **인용된 광고 문구가 사라진다** —
#:    결정문은 위법 문구도 따옴표로 인용한다(「'바르는게 운동입니다'」).
#:    그것이 우리가 가장 원하는 데이터다. 그래서 **앞말을 요구한다.**
_BRAND = re.compile(
    r"(영업표지|상표|서비스표|상호)(\s*(?:인|는|가|를|은)?\s*)['‘“「『]([^'’”」』\n]{1,20})['’”」』]"
)


def mask_brand(text: str, log: list[dict] | None = None) -> str:
    """「영업표지 'X'」의 X 만 `[상표]` 로. 앞말과 따옴표는 남긴다."""
    return _BRAND.sub(
        lambda m: (
            _note(log, "영업표지", m.group(3), MASK_BRAND)
            or f"{m.group(1)}{m.group(2)}'{MASK_BRAND}'"
        ),
        text,
    )


class MaskPolicyError(RuntimeError):
    """마스킹 정책이 없는 원천을 지우려 했다."""


def apply_policy(text: str, bare: str, source: str, log: list[dict] | None = None) -> str:
    """레지스트리가 그 원천에 정한 것만 지운다 (`POLICY`).

    🚨 순서가 있다 — 앵커(정확) → 자리(넓음) → 주소 → 상표 → 사람.
       넓은 것을 먼저 돌리면 앵커가 이미 지워진 자리를 또 훑어 `[업체]` 가 겹친다.

    🔴 **모르는 원천은 통과시키지 않고 거부한다** (D-72 fail-closed · 2026-09-06).

       `data_sources.yaml` 을 훑어 보니 `masking:` 을 선언한 원천이 **5종뿐**이다.
       `mfds_press`(부당광고 점검 보도자료)·`mfds_casebook`(사례집)에는 없는데,
       **둘 다 적발 업체명이 나오는 문서다.**

       🚨 선언이 없는 것이 「마스킹 불필요」인지 「안 적은 것」인지 **구분이 안 된다.**
          조용히 통과시키면 그 구분이 영영 안 생긴다 — 「돌아갔으니 됐다」가 되기 때문이다.
          그래서 멈추고, **레지스트리를 채우라고 말한다.** 판단은 2인 확인이 한다.
    """
    if source not in POLICY:
        raise MaskPolicyError(
            f"{source!r} 의 마스킹 정책이 없다.\n"
            f"  🚨 조용히 통과시키지 않는다 (D-72 fail-closed) — 선언이 없는 것이\n"
            f"     「불필요」인지 「안 적은 것」인지 구분이 안 되기 때문이다.\n"
            f"  고치는 법 — ① data_sources.yaml 의 {source!r} 에 masking: 을 적는다\n"
            f"              ② 2인 확인을 거친다 (게이트 15)\n"
            f"              ③ preprocess/mask.py 의 POLICY 에 같은 뜻으로 옮긴다\n"
            f"     🚨 마스킹이 정말 불필요하다면 그 판단도 masking: 에 적는다 — 빈 칸으로 두지 않는다."
        )
    todo = POLICY[source]
    # 🔴 **축을 선언대로 건다** (D-157). 예전에는 `org` 안에서 사람까지 걸었다.
    # 🚨 **자리는 그대로 둔다 — 앵커 바로 뒤다.** 축을 떼면서 사람을 맨 앞으로 옮겼더니
    #    치환이 416 → 398 로 줄었다(D-143 이 「본문바뀜 8」로 즉시 잡았다).
    #    앵커가 먼저 돌아야 하는 이유가 있다 — 앵커는 **정확**하고 사람 규칙은 넓다.
    # ⛔ docstring 은 「앵커 → 자리 → 주소 → 상표 → **사람**」이라 적고 있었는데
    #    코드는 사람을 앵커와 함께 **맨 앞**에서 돌리고 있었다. **적어 둔 순서와 도는 순서가 달랐다.**
    #    지금은 코드가 맞다고 보고 그대로 두되, 그 사실을 여기 적는다 (D-157).
    if "org" in todo:
        text = mask(text, bare, log)  # 앵커만
        if "person" in todo:
            text = mask_person(text, log)  # 앵커 바로 뒤 — 예전과 같은 자리
        names = doc_org_names(text)  # 🚨 자리 치환 **전에** 캔다 — 치환 뒤엔 이름이 없다
        text = mask_org_slots(text, log)
        text = mask_org_foreign(text, log)  # 외국 법인격 — 여러 어절 상호까지 (2026-09-08)
        text, _ = mask_org_bare(text, names, log)  # 2패스 — 같은 문서의 맨몸 언급
        text = mask_paren_alias(text, log)  # 마스킹 직후 괄호 안 원어 표기
        # ⛔ **제3자 상호는 여기서 지우지 않는다** (2026-09-17 팀장 판정 · D-233).
        #    레지스트리의 「업체명 마스킹」은 **피심인**을 뜻한다 — 경쟁사·거래처·인용된 회사가
        #    아니다. 그래서 `bare_org_names()` 가 잡는 이름들(「보람아파트」·「[업체]전자」)은
        #    **선언 범위 밖**이고, 여기에 치환을 걸면 코드가 원장을 넘어선다 (D-54 — 원장이
        #    원본이고 코드가 사본이다).
        #    ★ 그 이름들은 **지우는 문제가 아니라 공개 문서에 들어오는 문제**다 —
        #      `residual_bare_orgs()` 를 게이트가 쓴다 (D-216 의 ⬜ ① · D-230 의 연장).
        #    ⬜ 뜻을 바꾸려면 레지스트리 `masking:` 문언부터 고치고 2인 확인을 거친다 (게이트 15).
    elif "person" in todo:
        text = mask_person(text, log, wide=source in PERSON_ALL_NAMES)
    if "addr" in todo:
        text = mask_address(text, log)
    if "brand" in todo:
        text = mask_brand(text, log)
    return text


def _iter_ftc(limit: int | None):
    d = RAW / "ftc"
    for n, p in enumerate(sorted(d.glob("*.xml")), 1):
        if limit and n > limit:
            return
        try:
            root = ET.parse(p).getroot()
        except ET.ParseError:
            yield p.name, "", "", "", 0
            continue
        raw, bare = anchor_ftc(root)
        body = "\n".join(_t(root, t) for t in ("주문", "결정요지", "이유"))
        yield p.name, raw, bare, body, body.count("피심인")


def _iter_mfds(limit: int | None):
    d = RAW / "mfds_sanctions"
    n = 0
    for p in sorted(d.glob("page_*.json")):
        obj = json.loads(p.read_text(encoding="utf-8"))
        for row in obj.get("I0470", {}).get("row", []):
            n += 1
            if limit and n > limit:
                return
            raw = (row.get("PRCSCITYPOINT_BSSHNM") or "").strip()
            yield f"{p.name}#{n}", raw, strip_legal(raw), (row.get("VILTCN") or ""), 0


ITER = {"ftc": _iter_ftc, "mfds_sanctions": _iter_mfds}


