def to_natural(text: str) -> str:
    """자국을 원천 표기(`○`)로 바꾼다 — **학습 입력을 만들 때만** 쓴다 (D-166).

    ★ 한 방향으로만 간다. `[대표]` → `○○○` 는 언제든 되지만 **반대는 안 된다** —
      ○ 로 저장하면 원천이 숫자·URL 을 가린 ○ 와 섞여 되돌릴 수 없다.
    🔴 그래서 **저장은 자국으로** 한다. D-152(분류는 정규화문, 저장은 원문)와 같은 모양이다.

    🚨 이 결과를 파일로 저장하지 않는다 — 저장하는 순간 구분이 사라진 판이 원본이 된다.

    ⬜ **2026-09-08 현재 부르는 곳이 없다.** 조사를 살리고 나니 「대표이사 [대표]을 각각
       고발한다」로 문법이 안 깨져, 대괄호가 오히려 **가려진 자리라고 말해 준다.**
       🚨 대괄호 토큰이 학습에 실제로 해로운지는 **모델을 붙여 봐야 안다** — 지금은 못 잰다.
       이 함수는 그 판단을 **나중에 할 수 있게 열어 두는 것**이고, 끝까지 안 쓰이면 지운다.
       ★ D-146(부르지 않는 검사는 없는 검사)이 경계한 모양이라 여기 적어 둔다 —
         다만 이것은 게이트가 아니라 변환이라 「안 불러서 못 잡는」 위험은 없다.
    """
    return MARK_RE.sub(lambda m: NATURAL[m.group(0)], text)


