    by = collections.Counter((r["구분"], r["칸"]) for r in recs)
    gubuns = sorted({r["구분"] for r in recs})
    print(f"전사 {len(recs)}행 → {OUT}")
    print(f"{'구분':<34} {'금지':>4} {'허용':>4}")
    tb = ta = 0
    for g in gubuns:
        b, a = by[(g, "금지")], by[(g, "허용")]
        tb += b
        ta += a
        print(f"{g:<34} {b:>4} {a:>4}")
    print(f"{'합계':<34} {tb:>4} {ta:>4}")
    cond = collections.Counter(r["조건"] for r in recs if r["칸"] == "허용")
    print(f"\n허용 {ta}종의 조건 — {dict(cond)}")
    dup = [t for t, c in collections.Counter(r["표현"] for r in recs).items() if c > 1]
