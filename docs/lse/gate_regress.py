def main() -> None:
    b = sum(not check(o, s).passed for o, s in BAD)
    g = sum(check(o, s).passed for o, s in OK)
    print(f"위험 출력 막음 {b}/{len(BAD)} · 정상 통과 {g}/{len(OK)}")
    for o, s in BAD:
        if check(o, s).passed:
            print("  ⛔ 통과함:", s)
    for o, s in OK:
        r = check(o, s)
        if not r.passed:
            print("  ⛔ 막힘:", s, r.reasons)
    pm = sum((not check(a, b, persona=True).passed) == bad for a, b, bad in PERSONA)
    print(f"2단계(말투) 맞음 {pm}/{len(PERSONA)}")
    for a, b, bad in PERSONA:
        r = check(a, b, persona=True)
        if (not r.passed) != bad:
            print("  ⛔ 말투:", b, r.reasons)
    tr, ev = t.load_rows("v12")
    seen, n, fp = set(), 0, collections.Counter()
    for r in tr + ev:
        out = r.get("output") or {}
        body = out.get("body") if isinstance(out, dict) else None
        if not body or (r["input"], body) in seen:
            continue
        seen.add((r["input"], body))
        n += 1
        res = check(r["input"], body)
        if not res.passed:
            for x in res.reasons:
                fp[x.split(":")[0]] += 1
            fp["_rows"] += 1
    print(
        f"학습·평가 정답 {n} 중 보류 {fp['_rows']} ({fp['_rows'] / n:.1%})",
        {k: v for k, v in fp.most_common() if k != "_rows"},
    )


if __name__ == "__main__":
    main()
