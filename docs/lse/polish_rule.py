def form_in(s1: str, category: str | None) -> str | None:
    """`usage_dict.form_of` 와 같은 읽기(끝 두 낱말 → 문장 전체 · 가장 뒤에서 맞은 모양)를 **품목이 허락한 모양 안에서만** 한다."""
    allowed = ALLOWED.get(category or "")
    if allowed is None:
        return None  # 품목을 모르면 붙이지 않는다(다듬기는 식품 · 건기식 · 화장품에서만 · 10-13)
    words = _UNIT_TAIL.sub("", s1.strip()).split()
    for span in (words[-2:], words):
        text = " ".join(span)
        best = None
        for i, (name, pat, _) in enumerate(FORMS):
            if name not in allowed:
                continue
            for m in re.finditer(pat, text):
                key = (m.end(), -i)
                if best is None or key > best[0]:
                    best = (key, name)
        if best:
            return best[1]
    return None


def polish_by_rule(s1: str, category: str | None) -> str | None:
    """1단계 문장 + 모양에 맞는 쓰는 법 문구. 품목을 모르거나 모양을 못 읽으면 None(담백한 안만)."""
    form = form_in(s1, category)
    if form is None or form not in SAY:
        return None
    # 🔄 10-15 — 문구 고르는 낱말은 **제품 이름(끝 두 낱말)** 에서만 찾는다 — 「국산 생강을 꿀에 절여 숙성한 생강청」의 「꿀」을 꿀 제품으로 읽지 않게
    name = " ".join(_UNIT_TAIL.sub("", s1.strip()).split()[-2:])
    for pat, say in SAY[form]:
        if pat is None or re.search(pat, name):
            return f"{s1.rstrip(' .,')}, {say}"
    return None
