    if form is None or form[0] not in HOW:
        return HOW_NONE
    hint = HOW[form[0]]
    for pat, part in BODY:
        if re.search(pat, s1):
            return f"{hint} · 바르는 자리: {part}" if form[0] not in {"캡슐", "구미", "액상스틱", "분말", "청", "음료", "차", "양념", "조리", "간식"} else hint
    return hint
