_UNIT_TAIL = re.compile(
    r"(?:\s*[\d.,]+\s*(?:ml|mL|L|g|kg|㎏|포|개|정|캡슐|병|매|봉|팩|구|cm|켤레|장|입|인분|ea|EA)?|\s*\+)+$"
)


def form_of(s1: str) -> tuple[str, set[str]] | None:
    """1단계 문장의 제품 모양과 허용 동사. 못 읽으면 None.
    🔄 제품을 말하는 **끝 낱말**부터 본다 — 「쌀가루로만 빚은 떡」은 가루가 아니라 떡이다. 끝 두 낱말 · 문장 전체 순으로, 가장 뒤에서 맞은 모양(「해남 꿀고구마」는 꿀이 아니라 고구마)"""
    words = _UNIT_TAIL.sub("", s1.strip()).split()
    for span in (words[-2:], words):
        text = " ".join(span)
        best = None
        for i, (name, pat, allowed) in enumerate(FORMS):
            for m in re.finditer(pat, text):
                key = (m.end(), -i)
                if best is None or key > best[0]:
                    best = (key, name, allowed)
        if best:
            return best[1], best[2]
    return None


def usage_mismatch(s1: str, new_words: list[str]) -> list[str]:
    """2단계가 새로 넣은 낱말 중 **제품 모양에 허용되지 않은 쓰는 법**. 빈 목록이면 통과."""
    form = form_of(s1)
    # 모양을 못 읽으면(생활용품 · 서비스 …) 먹는 말 · 바르는 말만 막는다 — 서비스 범위(건기식 · 식품 · 화장품)의 쓰는 법을 지어내는 것이 문제다
    allowed = form[1] if form else set(VERB) - _EAT_OR_APPLY
    bad = []
    for w in new_words:
        if NEUTRAL.search(w):
            continue
        for verb, rx in _VERB_RE.items():
            if rx.search(w) and verb not in allowed:
                bad.append(f"{w}({verb} · {form[0] if form else '모양 모름'})")
                break
    return bad


